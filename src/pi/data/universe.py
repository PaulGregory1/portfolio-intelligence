"""Investment universe: ~40 real ETFs and stocks with descriptive metadata.

Names and tickers are real; `esg_score` and the synthetic-price parameters (`mu`, `sigma`)
are invented and only used when market data cannot be downloaded.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict

AssetClass = Literal["equity", "fixed_income", "alternatives", "cash"]
Currency = Literal["CHF", "EUR", "USD"]
CURRENCIES: tuple[Currency, ...] = ("CHF", "EUR", "USD")


class Instrument(BaseModel):
    model_config = ConfigDict(frozen=True)

    ticker: str
    name: str
    asset_class: AssetClass
    sub_asset_class: str
    region: str
    currency: Currency
    ter_pct: float  # total expense ratio, in percent per year (0 for single stocks)
    esg_score: int  # 0-100, synthetic
    description: str
    yf_ticker: str | None  # Yahoo Finance symbol, None if synthetic only
    # Parameters of the synthetic price generator (annualised drift and volatility).
    mu: float
    sigma: float
    income_yield: float  # dividend or coupon yield per year, paid quarterly


def _i(
    ticker: str,
    name: str,
    asset_class: AssetClass,
    sub_asset_class: str,
    region: str,
    currency: Currency,
    ter_pct: float,
    esg_score: int,
    yf_ticker: str | None,
    mu: float,
    sigma: float,
    income_yield: float,
    description: str,
) -> Instrument:
    return Instrument(
        ticker=ticker,
        name=name,
        asset_class=asset_class,
        sub_asset_class=sub_asset_class,
        region=region,
        currency=currency,
        ter_pct=ter_pct,
        esg_score=esg_score,
        description=description,
        yf_ticker=yf_ticker,
        mu=mu,
        sigma=sigma,
        income_yield=income_yield,
    )


